BEGIN;

CREATE TABLE public.profile_skills (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

    profile_id uuid NOT NULL
        REFERENCES public.profiles(id)
        ON DELETE CASCADE,

    name text NOT NULL,
    proficiency text NOT NULL,

    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT profile_skills_name_check
        CHECK (
            name ~ '[^[:space:]]'
            AND char_length(name) <= 100
            AND name = btrim(name)
        ),

    CONSTRAINT profile_skills_proficiency_check
        CHECK (
            proficiency IN (
                'Beginner',
                'Intermediate',
                'Advanced',
                'Expert'
            )
        )
);

-- Prevent one user from adding both "TypeScript" and "typescript".
-- Because profile_id is the first indexed value, this also supports
-- queries that list one user's skills.
CREATE UNIQUE INDEX profile_skills_profile_name_idx
    ON public.profile_skills (profile_id, lower(name));

ALTER TABLE public.profile_skills
    ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.profile_skills
    FROM PUBLIC, anon, authenticated;

GRANT SELECT, DELETE
    ON TABLE public.profile_skills
    TO authenticated;

-- id and created_at are generated by the database.
GRANT INSERT (profile_id, name, proficiency)
    ON TABLE public.profile_skills
    TO authenticated;

-- Users cannot change an entry's id, owner, or creation time.
GRANT UPDATE (name, proficiency)
    ON TABLE public.profile_skills
    TO authenticated;

CREATE POLICY "Users can view own skills"
    ON public.profile_skills
    FOR SELECT
    TO authenticated
    USING ((SELECT auth.uid()) = profile_id);

CREATE POLICY "Users can add own skills"
    ON public.profile_skills
    FOR INSERT
    TO authenticated
    WITH CHECK ((SELECT auth.uid()) = profile_id);

CREATE POLICY "Users can update own skills"
    ON public.profile_skills
    FOR UPDATE
    TO authenticated
    USING ((SELECT auth.uid()) = profile_id)
    WITH CHECK ((SELECT auth.uid()) = profile_id);

CREATE POLICY "Users can delete own skills"
    ON public.profile_skills
    FOR DELETE
    TO authenticated
    USING ((SELECT auth.uid()) = profile_id);

COMMIT;